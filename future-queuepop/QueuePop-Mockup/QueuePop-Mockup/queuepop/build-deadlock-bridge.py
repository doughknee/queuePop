"""Embed the approved study in QueuePop without changing its source or design."""
from pathlib import Path
import json
import re

here = Path(__file__).resolve().parent
source = here.parent / 'deadlock'
html = (source / 'index.html').read_text(encoding='utf-8')
body = re.search(r'<body>(.*)</body>', html, re.S).group(1)
body = re.sub(r'<header class="masthead">.*?</header>', '', body, flags=re.S)
body = body.replace('assets/', '../deadlock/assets/')
body = body.replace('href="comparison.html"', 'href="../deadlock/comparison.html"')
body = body.replace('href="#/', 'href="#/deadlock/')

styles = []
fonts = []
for name in re.findall(r'<link rel="stylesheet" href="([^"]+)"', html):
    css = (source / name).read_text(encoding='utf-8').replace('assets/', '../deadlock/assets/')
    fonts.extend(re.findall(r'@font-face\{[^}]+\}', css))
    css = re.sub(r'@font-face\{[^}]+\}', '', css)
    # Only document-root selectors change; component rules remain intact.
    css = css.replace(':root', '.deadlock-surface')
    css = re.sub(r'(?<![\w-])(?:body|html)(?![\w-])', '.deadlock-surface', css)
    styles.append(css)
css = ':host{display:block}.deadlock-surface{font-size:16px;line-height:normal;text-align:start}\n' + '\n'.join(styles)
(here / 'deadlock-fonts.css').write_text('\n'.join(fonts), encoding='utf-8')

scripts = '\n'.join((source / name).read_text(encoding='utf-8') for name in ('archive-data.js', 'casework.js', 'app.js'))
scripts = scripts.replace('assets/', '../deadlock/assets/')
scripts = scripts.replace("window.addEventListener('popstate',() => routeFromAddress());", '')
scripts = scripts.replace("window.addEventListener('hashchange',() => routeFromAddress());", '')
scripts = scripts.replace('routeFromAddress(false);', '')
scripts = scripts.replace("if(!sheet.hidden && activePanel", "if(!host.hidden && !sheet.hidden && activePanel")

adapter = r'''// Generated by build-deadlock-bridge.py. Approved source remains in ../deadlock/.
window.createDeadlockView = function(host) {
  const ownerDocument = window.document;
  const shadow = host.attachShadow({mode:'open'});
  shadow.innerHTML = '<style>' + __CSS__ + '</style><div class="deadlock-surface">' + __HTML__ + '</div>';
  const surface = shadow.querySelector('.deadlock-surface');
  // Scope DOM operations while sharing the application title and header status.
  const document = {
    body: surface,
    querySelector(selector) { return selector === '#header-status' ? ownerDocument.querySelector(selector) : shadow.querySelector(selector); },
    querySelectorAll: selector => shadow.querySelectorAll(selector),
    createElement: tag => ownerDocument.createElement(tag),
    addEventListener: (...args) => shadow.addEventListener(...args),
    get title() { return ownerDocument.title; },
    set title(value) { ownerDocument.title = value; }
  };
  const location = { get hash() { return window.location.hash.replace(/^#\/deadlock(?=\/|$)/, '#') || '#/'; } };
  const history = {
    pushState(state, title, hash) {
      window.history.pushState(state, title, '#/deadlock' + hash.slice(1));
    }
  };
__SCRIPTS__
  return {
    show(focus = true) {
      const route = location.hash.replace(/^#\/?/, '').split('/')[0];
      renderPage(pageNames[route] ? route : '', focus);
    },
    focus() {
      const target = shadow.querySelector(activePanel ? '#sheet-title' : '#arrival-title');
      target.tabIndex = -1;
      target.focus();
    }
  };
};
// Warm arrival assets without delaying the shared application shell.
for (const source of ['../deadlock/assets/city.webp', '../deadlock/assets/heroes/ivy.webp', '../deadlock/assets/heroes/infernus.webp']) {
  const image = new Image();
  image.src = source;
  image.decode().catch(() => {});
}
document.fonts.load('400 16px Germania').catch(() => {});
document.fonts.load('700 16px Barlow').catch(() => {});
'''
adapter = adapter.replace('__CSS__', json.dumps(css)).replace('__HTML__', json.dumps(body)).replace('__SCRIPTS__', scripts)
(here / 'deadlock-view.js').write_text(adapter, encoding='utf-8')

# Old bookmarks enter the shared app once; in-app links never use this document.
(here / 'deadlock.html').write_text('''<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>Deadlock · QueuePop</title><style>html{background:#141618;color:#eeeae1;font:16px Arial}</style>
<script>location.replace('index.html#/deadlock' + (location.hash.replace(/^#/, '') || '/'));</script>
</head><body><a href="index.html#/deadlock">Open Deadlock in QueuePop</a></body></html>
''', encoding='utf-8')
