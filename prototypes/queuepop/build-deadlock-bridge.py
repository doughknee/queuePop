"""Reuse the approved Deadlock study without editing its source or artwork."""
from pathlib import Path
import re

here = Path(__file__).resolve().parent
source = here.parent / 'deadlock'
html = (source / 'index.html').read_text(encoding='utf-8')

def asset_reference(match):
    attr, value = match.groups()
    if value.startswith(('#', 'http:', 'https:')):
        return match.group(0)
    if value in ('app.js', 'casework.js'):
        return f'{attr}="deadlock-{value}"'
    return f'{attr}="../deadlock/{value}"'

html = re.sub(r'(src|href)="([^"]+)"', asset_reference, html)
html = html.replace('</head>', '  <link rel="stylesheet" href="shell.css">\n  <script src="shell.js" defer></script>\n</head>')
html = html.replace('<body>', '<body data-bridge="deadlock">')
html = re.sub(r'<header class="masthead">.*?</header>', '<header id="qp-header"></header>', html, flags=re.S)
(here / 'deadlock.html').write_text(html, encoding='utf-8')
for name in ('app.js', 'casework.js'):
    code = (source / name).read_text(encoding='utf-8').replace('assets/', '../deadlock/assets/')
    (here / f'deadlock-{name}').write_text('// Generated by build-deadlock-bridge.py. Edit the approved source, then regenerate.\n' + code, encoding='utf-8')
