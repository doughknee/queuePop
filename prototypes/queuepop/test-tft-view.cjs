const assert = require('node:assert/strict');
const vm = require('node:vm');
const fs = require('node:fs');
const listeners = {};
const source = 'http://127.0.0.1:4318/queuepop/tft-field-guide/index.html';
const child = { location: { hash: '#home', replace(url) { assert.equal(url.split('#')[0], source); this.hash = new URL(url).hash; } }, addEventListener(type, fn) { listeners[type] = fn; } };
const frame = { contentWindow: child, addEventListener(type, fn) { this[type] = fn; }, focus() {} };
const host = { hidden: false, count: 0, append() { this.count++; } };
const context = { URL, window: {}, location: { href: 'http://127.0.0.1:4318/queuepop/#/tft/planner', hash: '#/tft/planner' }, document: { createElement() { return frame; } }, history: { replaceState(a, b, url) { context.location.hash = url; } } };
vm.runInNewContext(fs.readFileSync(__dirname + '/tft-view.js', 'utf8'), context);
const view = context.window.createTftView(host);
view.show();
assert.equal(frame.src, source + '#playground');
frame.load();
child.location.hash = '#comp-0';
listeners.hashchange();
assert.equal(context.location.hash, '#/tft/comp-0');
context.location.hash = '#/tft/comps';
view.show();
assert.equal(child.location.hash, '#comps');
assert.equal(host.count, 1, 'Switching games must reuse the loaded Field Guide');
host.hidden = true;
child.location.hash = '#home';
listeners.hashchange();
assert.equal(context.location.hash, '#/tft/comps', 'Hidden TFT must not change another game route');
context.location.hash = '#/tft/history';
view.show(false);
assert.equal(child.location.hash, '#home', 'Old history links must reach the replacement');
console.log('TFT integration checks passed.');
